// Writes supabase/seed.sql from data/landmarks.ts: one upsert per landmark,
// so re-running the seed updates rows instead of duplicating them.
//
//   npm run db:seed:sql
//
// Then paste supabase/seed.sql into the Supabase SQL editor (it needs no keys).
import { writeFileSync } from "node:fs";
import { landmarks } from "../data/landmarks";
import { landmarkToRow, type LandmarkRow } from "../lib/landmark-row";

const COLUMNS: (keyof LandmarkRow)[] = [
  "id",
  "name",
  "category",
  "region",
  "description",
  "lat",
  "lng",
  "elevation_m",
  "area_km2",
  "image",
  "image_credit",
  "sort_order",
  "details",
];

// SQL literal for one value. Strings are single-quoted with quotes doubled;
// `details` becomes JSON cast to jsonb.
function literal(value: unknown): string {
  if (value === null || value === undefined) return "null";
  if (typeof value === "number") return String(value);
  if (typeof value === "object")
    return `'${JSON.stringify(value).replaceAll("'", "''")}'::jsonb`;
  return `'${String(value).replaceAll("'", "''")}'`;
}

const rows = landmarks.map((landmark, i) => landmarkToRow(landmark, i));
const values = rows
  .map((row) => `  (${COLUMNS.map((c) => literal(row[c])).join(", ")})`)
  .join(",\n");
const updates = COLUMNS.filter((c) => c !== "id")
  .map((c) => `  ${c} = excluded.${c}`)
  .join(",\n");

const sql = `-- Generated by scripts/generate-seed.ts from data/landmarks.ts. Do not edit
-- by hand: change data/landmarks.ts and run \`npm run db:seed:sql\`.
-- ${rows.length} landmarks. Safe to run again: existing rows are updated.

insert into public.landmarks (${COLUMNS.join(", ")})
values
${values}
on conflict (id) do update set
${updates};
`;

const path = new URL("../supabase/seed.sql", import.meta.url);
writeFileSync(path, sql);
console.log(`Wrote ${rows.length} landmarks to supabase/seed.sql`);
